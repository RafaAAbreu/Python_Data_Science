# Variavel para Armazenamento

nome_aluno = "Rocky"
idade_aluno = 15
media_aluno = 8.45

print('Nome de Aluno %s, ele tem %d anos e sua média %f' %(nome_aluno,idade_aluno,media_aluno))
print('Nome de Aluno %s, ele tem %d anos e sua média %.2f' %(nome_aluno,idade_aluno,media_aluno))
print('Nome de Aluno é {}, ele tem {} anos e sua média {:.2f}' .format(nome_aluno,idade_aluno,media_aluno))
print('Nome de Aluno é {nome_aluno}, ele tem {idade_aluno} anos e sua média {media_aluno}')
